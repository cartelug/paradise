// V31 photography: prepares the photographs dropped into source-assets/v31-photography/ (see credits.json there) in the same
// way as the V24 pipeline: a 3:2 crop with each photo's own crop focus, at 640, 1280 and 1920 px, as AVIF and WebP. Photos
// that are not there yet are skipped. It then writes src/data/v31-photography.ts, which tells the site which slots have a
// V31 photograph; every other slot keeps its V24 picture. Run from website/: node scripts/prepare-v31-photography.mjs
import sharp from 'sharp';
import { access, readFile, writeFile } from 'node:fs/promises';

const folder = 'source-assets/v31-photography';
const { photos } = JSON.parse(await readFile(`${folder}/credits.json`, 'utf8'));
const prepared = [];
for (const photo of photos) {
  const input = `${folder}/${photo.file}`;
  try { await access(input); } catch { console.log(`Skipped ${photo.slot}: ${photo.file} is not in ${folder} yet.`); continue; }
  if (!photo.alt?.trim()) throw new Error(`${photo.file}: write a truthful alt text for the new picture in credits.json first.`);
  if (!photo.source?.trim()) throw new Error(`${photo.file}: say where it comes from in credits.json ("AI-generated, illustrative" for generated pictures).`);
  // A generated picture is illustrative: "a resort" is fine, "the Example Resort" is not.
  if (/ai-generated/i.test(photo.source) && /\b[A-Z][\w'-]+ (Resort|Hotel|Lodge|Camp|Yacht)s?\b/.test(photo.alt)) {
    throw new Error(`${photo.file}: an AI-generated picture must not be described as a named resort, hotel or yacht.`);
  }
  const { width = 0, height = 0 } = await sharp(input).metadata();
  if (Math.max(width, height) < 1600) console.warn(`Warning: ${photo.file} is only ${width} x ${height}; 2400 x 1600 or larger is recommended.`);
  const asset = `${photo.slot}-v31`;
  for (const size of [640, 1280, 1920]) {
    const image = () => sharp(input).rotate().resize(size, Math.round(size / 1.5), { fit: 'cover', position: photo.crop || 'centre', withoutEnlargement: false });
    await image().avif({ quality: 64, effort: 4 }).toFile(`public/images/${asset}-${size}.avif`);
    await image().webp({ quality: 85, effort: 4 }).toFile(`public/images/${asset}-${size}.webp`);
  }
  prepared.push({ slot: photo.slot, asset, alt: photo.alt.trim(), source: photo.source.trim() });
  console.log(`Prepared ${asset} from ${photo.file} (${photo.source}).`);
}
await writeFile('src/data/v31-photography.ts', `// Generated by scripts/prepare-v31-photography.mjs from source-assets/v31-photography/credits.json. Only photographs that
// were present and prepared are listed; every other slot falls back to the V24 photography.
export const v31Photography: { slot: string; asset: string; alt: string; source: string }[] = ${JSON.stringify(prepared, null, 2)};
`);
console.log(`${prepared.length} of ${photos.length} V31 photographs prepared; the rest keep their V24 pictures.`);
