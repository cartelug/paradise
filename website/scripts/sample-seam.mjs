// Samples the true top edge of the Who We Are artwork and writes it as CSS, so the
// hero's bottom fade and the section's top fade meet on the identical colours.
import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const stops = 24;
const edge = async (file, rows) => {
  const { data, info } = await sharp(resolve(root, 'public/images', file)).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const colours = [];
  for (let i = 0; i < stops; i++) {
    const x0 = Math.floor((i / stops) * info.width), x1 = Math.max(x0 + 1, Math.floor(((i + 1) / stops) * info.width));
    let r = 0, g = 0, b = 0, n = 0;
    for (let y = 0; y < rows; y++) for (let x = x0; x < x1; x++) { const p = (y * info.width + x) * 3; r += data[p]; g += data[p + 1]; b += data[p + 2]; n++; }
    colours.push([r / n, g / n, b / n].map(Math.round));
  }
  // Light smoothing so single clouds never become hard bands.
  const smooth = colours.map((c, i) => [0, 1, 2].map(k => Math.round(((colours[i - 1] || c)[k] + 2 * c[k] + (colours[i + 1] || c)[k]) / 4)));
  const hex = c => '#' + c.map(v => v.toString(16).padStart(2, '0')).join('');
  return `linear-gradient(90deg, ${smooth.map((c, i) => `${hex(c)} ${(i / (stops - 1) * 100).toFixed(1)}%`).join(', ')})`;
};
const desktop = await edge('pardus-who-desktop-1536.webp', 3);
const mobile = await edge('pardus-who-mobile-853.webp', 3);
await writeFile(resolve(root, 'src/styles/seam-colors.css'), `/* Generated by scripts/sample-seam.mjs from the real top edge of the Who We Are artwork. */\n.home { --who-entry-gradient: ${desktop}; }\n@media (max-width: 999px) { .home { --who-entry-gradient: ${mobile}; } }\n`);
console.log('written');
