import sharp from 'sharp';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(project, 'source-assets/v44-destinations');
const output = resolve(project, 'public/images');
const { photos } = JSON.parse(await readFile(resolve(source, 'credits.json'), 'utf8'));
await mkdir(output, { recursive: true });
const registry = [];
for (const photo of photos) {
  const file = resolve(source, photo.file);
  const original = await sharp(file).metadata();
  const widths = [640, 1280, 1920].filter(width => width <= original.width);
  for (const width of widths) {
    const image = sharp(file).rotate().resize({ width, height: Math.round(width * 2 / 3), fit: 'cover', position: 'centre', withoutEnlargement: true });
    await image.clone().webp({ quality: 84, effort: 6 }).toFile(resolve(output, `${photo.asset}-${width}.webp`));
    await image.clone().avif({ quality: 55, effort: 5 }).toFile(resolve(output, `${photo.asset}-${width}.avif`));
  }
  registry.push({ ...photo, width: 1920, height: 1280, widths });
}
await writeFile(resolve(project, 'src/data/owner-photographs.ts'), `// Licensed photography; generated by scripts/prepare-owner-photographs.mjs.\nexport const ownerPhotographs = ${JSON.stringify(registry, null, 2)};\n`);
console.log(`Prepared ${registry.length} licensed destination photographs without enlargement.`);
