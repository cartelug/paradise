// V38 travel photographs: prepares the ten masters in source-assets/travel-photographs-2026-10-25/ (see manifest.json there)
// as responsive AVIF and WebP at their native 16:10 shape. Only widths the master supports are written (never enlarged), and
// nothing is cropped here: each picture is cropped by its container using the per-asset focal point below.
// It writes src/data/travel-photographs.ts, which photo() in src/data/photography.ts consults before the older registries.
// Run from website/: node scripts/prepare-travel-photographs.mjs   (add --force to re-encode files that already exist)
import sharp from 'sharp';
import { readFile, writeFile, access } from 'node:fs/promises';
const exists = file => access(file).then(() => true, () => false);
const force = process.argv.includes('--force');

const folder = 'source-assets/travel-photographs-2026-10-25';
const { files } = JSON.parse(await readFile(`${folder}/manifest.json`, 'utf8'));

// Which site photo slots each master fills, and where its main subject sits (object-position, % across / % down).
const placement = {
  'maldives.png': { slots: ['maldives'], position: '55% 38%' },
  'seychelles.png': { slots: ['seychelles'], position: '55% 46%' },
  'dubai.png': { slots: ['dubai'], position: '50% 52%' },
  'east-africa.png': { slots: ['safari-uganda', 'safari-family', 'journal-safari'], position: '88% 60%' },
  'europe.png': { slots: ['europe'], position: '15% 56%' },
  'zanzibar.png': { slots: ['zanzibar'], position: '64% 50%' },
  'yacht.png': { slots: ['yacht'], position: '40% 56%' },
  'executive.png': { slots: ['corporate'], position: '52% 62%' },
  'reset.png': { slots: ['reset', 'hero-maldives'], position: '22% 85%' },
  'celebration.png': { slots: ['celebration'], position: '85% 80%' },
};
const steps = [640, 960, 1280];
const prepared = [];
for (const file of files) {
  const where = placement[file.filename];
  if (!where) throw new Error(`${file.filename}: no placement defined.`);
  if (!file.suggested_alt?.trim()) throw new Error(`${file.filename}: missing alt text in manifest.json.`);
  const input = `${folder}/${file.filename}`;
  const { width, height } = await sharp(input).metadata();
  if (width !== file.width || height !== file.height) throw new Error(`${file.filename}: dimensions differ from manifest.json.`);
  const asset = `${file.filename.replace(/\.png$/, '')}-v38`;
  const widths = [...steps.filter(size => size < width), width];
  for (const size of widths) {
    const image = () => sharp(input).rotate().resize(size, Math.round(size * height / width), { fit: 'fill' });
    const avif = `public/images/${asset}-${size}.avif`, webp = `public/images/${asset}-${size}.webp`;
    if (force || !(await exists(avif))) await image().avif({ quality: 62, effort: 6 }).toFile(avif);
    if (force || !(await exists(webp))) await image().webp({ quality: 84, effort: 5 }).toFile(webp);
  }
  prepared.push({ asset, slots: where.slots, alt: file.suggested_alt.trim(), widths, width, height, position: where.position, source: 'AI-generated, illustrative' });
  console.log(`Prepared ${asset}: ${widths.join(', ')} px for ${where.slots.join(', ')}.`);
}
await writeFile('src/data/travel-photographs.ts', `// Generated by scripts/prepare-travel-photographs.mjs from source-assets/travel-photographs-2026-10-25/manifest.json.
// Each entry fills one or more photo slots (see photo() in photography.ts); position is the focal point used when a container crops it.
export type TravelPhotograph = { asset: string; slots: string[]; alt: string; widths: number[]; width: number; height: number; position: string; source: string };
export const travelPhotographs: TravelPhotograph[] = ${JSON.stringify(prepared, null, 2)};
`);
console.log(`${prepared.length} travel photographs prepared.`);
